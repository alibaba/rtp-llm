// These IDs are generated by vLLM's v1/worker/gpu/sample/gumbel.py.  The
// deterministic integer-built logits make this a direct compatibility probe
// for the two-stage (seed, absolute-position) Philox key and flipped-fp32
// Gumbel transform, rather than merely a replay test of our own kernel.
TEST_F(SpeculativeSamplingKernelTest, GumbelSample_MatchesVllmGolden) {
    constexpr int64_t rows       = 6;
    constexpr int64_t vocab_size = 4099;
    auto row = torch::arange(rows, int64Cuda()).view({rows, 1});
    auto col = torch::arange(vocab_size, int64Cuda()).view({1, vocab_size});
    auto logits = torch::remainder(row * 131 + col * 17, 257).to(torch::kFloat32) / 37.0F - 3.0F;
    auto seeds = torch::tensor(std::vector<int64_t>{0, 1, 42, 2147483647, 20260731, 987654321}, int64Cuda());
    auto positions = torch::tensor(std::vector<int64_t>{0, 1, 17, 1024, 65537, 999999}, int64Cuda());
    auto temperatures = torch::tensor({0.0F, 1.0F, 0.5F, 1.5F, 0.8F, 1.0F}, floatCuda());

    auto sampled = rtp_llm::gumbelSample(logits, seeds, positions, temperatures, false, true);
    auto expected = torch::tensor(std::vector<int64_t>{136, 187, 3883, 1609, 982, 610}, int64Cuda());
    EXPECT_TRUE(torch::equal(sampled, expected));

    auto shifted = rtp_llm::gumbelSample(logits, seeds, positions + 1, temperatures, false, true);
    auto shifted_expected = torch::tensor(std::vector<int64_t>{136, 2894, 967, 2162, 1826, 2541}, int64Cuda());
    EXPECT_TRUE(torch::equal(shifted, shifted_expected));
}

