TEST_F(SpeculativeSamplingKernelTest, GumbelSample_ProcessedProbabilitiesUseSameCoupling) {
    constexpr int64_t rows       = 6;
    constexpr int64_t vocab_size = 4099;
    auto row = torch::arange(rows, int64Cuda()).view({rows, 1});
    auto col = torch::arange(vocab_size, int64Cuda()).view({1, vocab_size});
    auto logits = torch::remainder(row * 131 + col * 17, 257).to(torch::kFloat32) / 37.0F - 3.0F;
    auto seeds = torch::tensor(std::vector<int64_t>{0, 1, 42, 2147483647, 20260731, 987654321}, int64Cuda());
    auto positions = torch::tensor(std::vector<int64_t>{0, 1, 17, 1024, 65537, 999999}, int64Cuda());
    auto temperatures = torch::tensor({0.0F, 1.0F, 0.5F, 1.5F, 0.8F, 1.0F}, floatCuda());
    auto temperature_divisor = torch::where(temperatures == 0.0F, torch::ones_like(temperatures), temperatures);
    auto probabilities = torch::softmax(logits / temperature_divisor.view({rows, 1}), -1);
    auto target_temperatures = torch::where(temperatures == 0.0F,
                                            torch::zeros_like(temperatures),
                                            torch::ones_like(temperatures));

    auto from_logits = rtp_llm::gumbelSample(logits, seeds, positions, temperatures, false, true);
    auto from_probs = rtp_llm::gumbelSample(probabilities, seeds, positions, target_temperatures, true, false);
    EXPECT_TRUE(torch::equal(from_logits, from_probs));
    EXPECT_TRUE(torch::equal(from_logits,
                             rtp_llm::gumbelSample(logits, seeds, positions, temperatures, false, true)));
    const auto sampled_argmax = from_logits[0].item<int64_t>();
    const auto expected_argmax = logits[0].argmax().item<int64_t>();
    EXPECT_EQ(sampled_argmax, expected_argmax);
}

