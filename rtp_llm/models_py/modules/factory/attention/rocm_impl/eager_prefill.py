"""Eager-only launch helpers; no graph capture and no numerical kernel changes."""

import inspect
import logging
import os
from functools import lru_cache

import torch


def short_query_backend(value: str) -> str:
    value = value.strip().lower()
    if value not in ("auto", "ck"):
        raise ValueError("RTP_LLM_ROCM_SHORT_QUERY_BACKEND must be auto or ck")
    return value


def allocate_pa_workspace(query, num_seqs, query_length, num_kv_heads, partitions):
    """Allocate one eager batch's scratch, reused in stream order across layers."""
    heads, head_dim = query.shape[1:]
    dtype = (
        torch.bfloat16
        if query.dtype in (torch.float8_e4m3fnuz, torch.float8_e4m3fn)
        else query.dtype
    )
    shape = (num_seqs, num_kv_heads, partitions, query_length * (heads // num_kv_heads))
    return {
        "output": torch.empty(
            (num_seqs * query_length, heads, head_dim), dtype=dtype, device=query.device
        ),
        "exp_sums": torch.empty(shape, dtype=torch.float32, device=query.device),
        "max_logits": torch.empty(shape, dtype=torch.float32, device=query.device),
        "temporary_output": torch.empty(
            (*shape, head_dim), dtype=dtype, device=query.device
        ),
    }


@lru_cache(maxsize=1)
def _ck_entrypoint():
    # AITER wheels have different APIs. Never bypass a public wrapper on an
    # unrecognized ABI; in particular newer KV block-scale/sink arguments must
    # not shift a positional call. Signature inspection is not on the hot path.
    try:
        from aiter.ops.mha import mha_batch_prefill

        expected = (
            "q k v cu_seqlens_q kv_indptr kv_page_indices max_seqlen_q max_seqlen_k "
            "dropout_p softmax_scale logits_soft_cap zero_tensors is_causal "
            "window_size_left window_size_right sink_size return_softmax_lse "
            "return_dropout_randval out bias alibi_slopes q_descale k_descale "
            "v_descale kv_block_descale kv_last_page_lens block_table seqlen_k sink_ptr gen"
        ).split()
        if list(inspect.signature(mha_batch_prefill).parameters) == expected:
            logging.info("ROCm eager CK prefill: compatible direct launch ABI")
            return mha_batch_prefill
    except (ImportError, TypeError, ValueError):
        pass
    logging.info("ROCm eager CK prefill: retaining public AITER entry point")
    return None


class CKPrefillLauncher:
    """Same causal CK kernel, skipping general-purpose wrapper work for native views.

    Restricted to eager BF16/FP16 vectorized K/V generated by AiterPrefillAttnOpPaged.
    FP8, unusual head geometry, non-contiguous input and unknown AITER ABIs keep
    the public path (including all its validation and conversion behavior).
    """

    def __init__(self, head_dim):
        self.head_dim = head_dim
        self.scale = head_dim**-0.5
        self.entrypoint = (
            _ck_entrypoint()
            if head_dim in (64, 128, 256)
            and os.environ.get("RTP_LLM_ROCM_CK_PREFILL_FAST_PATH", "1") == "1"
            else None
        )

    def __call__(
        self,
        q,
        k,
        v,
        cu_q,
        indptr,
        indices,
        max_q,
        max_k,
        *,
        causal,
        block_table,
        seqlen_k,
        q_descale=None,
        k_descale=None,
        v_descale=None,
        out=None,
    ):
        if (
            self.entrypoint is not None
            and q.is_cuda
            and q.dtype in (torch.float16, torch.bfloat16)
            and k.dtype == v.dtype == q.dtype
            and q.dim() == 3
            and k.dim() == v.dim() == 5
            and q.shape[-1] == self.head_dim
            and k.shape[-3] * (16 // k.element_size()) == self.head_dim
            and v.shape[-2] == self.head_dim
            and k.shape[-2] % (16 // k.element_size()) == 0
            and v.shape[-1] == 16 // k.element_size()
            and q.stride(-1) == k.stride(-1) == v.stride(-1) == 1
            and q_descale is None
            and k_descale is None
            and v_descale is None
        ):
            # All defaults match mha_batch_prefill_func: no dropout/LSE/sinks,
            # infinite window, no bias, no output padding or dtype conversion.
            return self.entrypoint(
                q,
                k,
                v,
                cu_q,
                indptr,
                indices,
                max_q,
                max_k,
                0.0,
                self.scale,
                0.0,
                False,
                causal,
                -1,
                -1,
                0,
                False,
                False,
                out,
                None,
                None,
                None,
                None,
                None,
                None,
                None,
                block_table,
                seqlen_k,
                None,
                None,
            )[0]

        import aiter

        return aiter.mha_batch_prefill_func(
            q,
            k,
            v,
            cu_q,
            indptr,
            indices,
            max_q,
            max_k,
            causal=causal,
            block_table=block_table,
            seqlen_k=seqlen_k,
            q_descale=q_descale,
            k_descale=k_descale,
            v_descale=v_descale,
            out=out,
        )
