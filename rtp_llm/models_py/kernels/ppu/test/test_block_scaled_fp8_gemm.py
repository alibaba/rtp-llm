"""Numerical order, frozen SGL outputs, and dynamic graph replay gates."""

import hashlib
import json
from pathlib import Path
from unittest import TestCase, main, skipUnless
from unittest.mock import patch

import numpy as np
import torch

from rtp_llm.device.device_type import is_ppu
from rtp_llm.models_py.kernels.ppu.block_scaled_fp8_gemm import fp8_block_scaled_matmul
from rtp_llm.models_py.kernels.ppu.fp8_quant import fp8_quantize_128
import rtp_llm.models_py.modules.factory.linear.ppu_impl.fp8_deepgemm_linear as linear


def sha(tensor):
    return hashlib.sha256(tensor.contiguous().view(torch.uint8).cpu().numpy().tobytes()).hexdigest()


@skipUnless(torch.cuda.is_available() and is_ppu(), "requires PPU")
class BlockScaledFp8GemmTest(TestCase):
    def test_frozen_sgl_outputs_and_operands(self):
        # Golden outputs were generated by the actual SGL 0.5.22 Triton
        # default kernel, not the candidate. Preserve its RNG sequence too.
        golden = json.loads(Path(__file__).with_name("test_block_scaled_fp8_sgl_golden.json").read_text())
        by_id = {r["id"]: r for r in golden["records"]}
        for n, k in [(2624, 6144), (16384, 2048), (6144, 16384), (24576, 6144),
                     (6144, 12288), (128, 6144), (4096, 2048), (3072, 6144), (6144, 1536)]:
            rng = np.random.default_rng(n * 100000 + k)
            # Keep FP32 initialization on CPU while the service owns VRAM.
            w = torch.from_numpy(rng.standard_normal((n, k), dtype=np.float32)).to(torch.float8_e4m3fn).cuda()
            ws = torch.from_numpy(rng.uniform(0.0005, 0.02, ((n + 127) // 128, k // 128)).astype(np.float32)).cuda()
            w_sha, ws_sha = sha(w), sha(ws)
            for m in [1, 3, 8, 17, 64, 1024]:
                with self.subTest(m=m, n=n, k=k):
                    x = torch.from_numpy(rng.standard_normal((m, k), dtype=np.float32)).bfloat16().cuda()
                    q, s = fp8_quantize_128(x)
                    y = fp8_block_scaled_matmul(q, w, s, ws)
                    record = {"id": f"m{m}_n{n}_k{k}", "q_sha256": sha(q), "scale_sha256": sha(s),
                              "weight_sha256": w_sha, "weight_scale_sha256": ws_sha, "output_sha256": sha(y)}
                    self.assertEqual(record, by_id[record["id"]])
                    del x, q, s, y
            del w, ws
            torch.cuda.empty_cache()

    def test_ragged_tiles_and_m_group_boundary(self):
        torch.manual_seed(739)
        for m in [1, 7, 16, 17, 32, 64, 65, 129, 2049]:
            q = torch.randint(-4, 5, (m, 384), device="cuda").to(torch.float8_e4m3fn)
            w = torch.randint(-4, 5, (73, 384), device="cuda").to(torch.float8_e4m3fn)
            s = torch.tensor([0.5, 2.0, 8.0], device="cuda").repeat(m, 1)
            ws = torch.tensor([[4.0, 0.25, 2.0]], device="cuda")
            expected = torch.zeros(m, 73, device="cuda")
            for j in range(3):
                expected += q[:, j * 128:(j + 1) * 128].float() @ w[:, j * 128:(j + 1) * 128].float().T * s[:, j, None] * ws[0, j]
            self.assertTrue(torch.equal(fp8_block_scaled_matmul(q, w, s, ws), expected.bfloat16()))

    def test_linear_opt_in_prequant_bias_and_graph_new_values(self):
        k, n, m = 256, 128, 7
        w = torch.ones(n, k, device="cuda", dtype=torch.float8_e4m3fn)
        ws = torch.ones(1, 2, device="cuda")
        bias = torch.ones(n, device="cuda", dtype=torch.bfloat16)
        with patch.object(linear.PpuFp8DeepGemmLinear, "_maybe_warmup"):
            layer = linear.PpuFp8DeepGemmLinear(w.view(k, n), ws.view(2, 1), bias=bias)
        x = torch.ones(m, k, device="cuda", dtype=torch.bfloat16)
        def forward():
            return layer(x, block_scaled=True)
        forward()
        torch.cuda.synchronize()
        graph = torch.cuda.CUDAGraph()
        stream = torch.cuda.Stream()
        stream.wait_stream(torch.cuda.current_stream())
        with torch.cuda.graph(graph, stream=stream):
            y = forward()
        for value in [0, -3, 2, 7]:
            x.fill_(value)
            graph.replay()
            self.assertTrue(torch.equal(y, torch.full_like(y, value * k + 1)))
            q, s = fp8_quantize_128(x)
            self.assertTrue(torch.equal(y, layer(q, input_scales=s, block_scaled=True)))
        def native(a, b, output):
            output.fill_(7)
        with patch.object(linear, "fp8_gemm_nt", side_effect=native) as native_call:
            self.assertTrue(torch.equal(layer(x), torch.full_like(y, 8)))
            native_call.assert_called_once()
        empty = layer(torch.empty(0, k, device="cuda", dtype=torch.bfloat16), block_scaled=True)
        self.assertEqual(empty.shape, (0, n))
        self.assertEqual(empty.dtype, torch.bfloat16)

    def test_output_reuse_and_contract_errors(self):
        q = torch.ones(3, 256, device="cuda", dtype=torch.float8_e4m3fn)
        w = torch.ones(73, 256, device="cuda", dtype=torch.float8_e4m3fn)
        s = torch.ones(3, 2, device="cuda")
        ws = torch.ones(1, 2, device="cuda")
        out = torch.empty(3, 73, device="cuda", dtype=torch.bfloat16)
        self.assertIs(fp8_block_scaled_matmul(q, w, s, ws, out=out), out)
        self.assertTrue(bool((out == 256).all()))
        with self.assertRaises(ValueError):
            fp8_block_scaled_matmul(q.bfloat16(), w, s, ws)
        with self.assertRaises(ValueError):
            fp8_block_scaled_matmul(q, w, s.T, ws)
        with self.assertRaises(ValueError):
            fp8_block_scaled_matmul(q, w, s, ws, out=out.float())


if __name__ == "__main__":
    torch.set_num_threads(1)
    main()
