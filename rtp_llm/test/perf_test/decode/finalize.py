"""Finalize decode runs with common results, summary, and matrix report."""

from __future__ import annotations

import copy
from pathlib import Path
from typing import Any, Dict, Mapping, Sequence, Union

from rtp_llm.test.perf_test.decode.report import generate_decode_report
from rtp_llm.test.perf_test.errors import PlanningError
from rtp_llm.test.perf_test.plan import AOneResourcePlan, ExecutionPlan, thaw
from rtp_llm.test.perf_test.results import RESULT_SCHEMA_VERSION, parse_result_envelope
from rtp_llm.test.perf_test.state import RunState
from rtp_llm.test.perf_test.storage import RunStore, atomic_write_json


def finalize_decode_run(
    root: Union[str, Path],
    *,
    plan: ExecutionPlan,
    run_id: str,
    case_results: Sequence[Mapping[str, Any]],
) -> Dict[str, Any]:
    """Validate and atomically persist every output generated by decode run."""
    if plan.mode != "decode" or plan.action != "run":
        raise PlanningError("decode finalization requires a decode run plan")
    resource = plan.resource_plan
    if plan.backend == "aone" and (
        not isinstance(resource, AOneResourcePlan) or resource.machine_count <= 1
    ):
        # Single-machine decode+aone cannot pass plan validation; a plan that
        # reaches finalization with backend=aone must be a multi-machine gang.
        raise PlanningError(
            "decode finalization with backend=aone requires a gang plan whose "
            "derived machine_count exceeds one"
        )
    if not isinstance(run_id, str) or not run_id:
        raise PlanningError("decode run_id must be a non-empty string")
    provided = {}
    for result in case_results:
        if not isinstance(result, Mapping) or not isinstance(
            result.get("case_id"), str
        ):
            raise PlanningError("decode case result must contain case_id")
        case_id = result["case_id"]
        if case_id in provided:
            raise PlanningError(f"duplicate decode case result: {case_id}")
        provided[case_id] = copy.deepcopy(dict(result))
    planned_ids = {case.case_id for case in plan.cases}
    if set(provided) != planned_ids:
        raise PlanningError("decode results must cover every planned case exactly once")
    ordered = []
    for case in plan.cases:
        result = provided[case.case_id]
        if result.get("identity") != thaw(case.identity):
            raise PlanningError(f"decode case identity mismatch: {case.case_id}")
        ordered.append(result)

    successful = sum(result.get("status") == "ok" for result in ordered)
    state = RunState.COMPLETED if successful == len(ordered) else RunState.PARTIAL
    summary = {
        "planned_cases": len(ordered),
        "successful_cases": successful,
        "failed_cases": len(ordered) - successful,
        "profiling_failed_cases": sum(
            (result.get("metrics") or {}).get("profiling", {}).get("status") == "failed"
            for result in ordered
        ),
    }
    resolved_model = plan.to_dict()["resolved_config"]["model"]
    model = {
        name: copy.deepcopy(resolved_model[name])
        for name in ("label", "type", "checkpoint", "topology")
    }
    envelope = {
        "schema_version": RESULT_SCHEMA_VERSION,
        "run_id": run_id,
        "mode": "decode",
        "backend": plan.backend,
        "status": state.value,
        "config_fingerprint": plan.config_fingerprint,
        "workload_fingerprint": plan.workload_fingerprint,
        "model": model,
        "summary": summary,
        "cases": ordered,
    }
    parse_result_envelope(envelope)
    report = generate_decode_report(ordered)

    root_path = Path(root)
    store = RunStore(root_path)
    for result in ordered:
        store.write_case(result["case_id"], result)
    store.write_final_result(envelope)
    summary_artifact = {
        "schema_version": 1,
        "run_id": run_id,
        "mode": "decode",
        "backend": plan.backend,
        "status": state.value,
        **summary,
    }
    store.write_summary(summary_artifact)
    atomic_write_json(root_path / "reports" / "decode_report.json", report)
    return envelope
