"""Fail-closed EP8 live-provider SR binding candidate; not yet qualified.

An independently reviewed per-EP-rank source/live manifest is mandatory.
The manifest must identify real global experts; local parameter indices alone
cannot establish source ownership. No manifest is generated by this module.
"""
import hashlib
import json
from pathlib import Path

from q36_ep_profile import expert_coordinate


def bind_all_ranks(model_chunks, manifest_path, expected_sha256):
    import torch
    import torch.distributed as dist
    from megatron.core import parallel_state as ps
    from megatron.core.distributed import DistributedDataParallel as MCoreDDP
    from megatron.core.transformer.module import Float16Module
    from bf16_fixed_tp4_coordinates_candidate import make_fixed_tp4_coordinates

    bindings = None
    error = None
    try:
        path = Path(manifest_path)
        if path.is_symlink() or not path.is_file(): raise ValueError('reviewed manifest is required')
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != expected_sha256: raise ValueError('manifest digest mismatch')
        manifest = json.loads(raw)
        if (manifest.get('schema') != 'q36-ep8-live-provider-sr-v1' or
            manifest.get('binding_scope') != 'independent-source-and-live-provider-reviewed' or
            (manifest.get('tp'), manifest.get('ep'), manifest.get('etp'), manifest.get('pp')) != (4, 8, 1, 1)):
            raise ValueError('reviewed EP8/ETP1 manifest required')
        if (ps.get_tensor_model_parallel_world_size() != 4 or ps.get_expert_model_parallel_world_size() != 8
                or dist.get_world_size(ps.get_expert_tensor_parallel_group()) != 1 or dist.get_world_size() != 8):
            raise ValueError('live distributed groups differ from reviewed TP4/EP8/ETP1')
        ep_rank = ps.get_expert_model_parallel_rank()
        rows = manifest.get('rank_parameters', {}).get(str(ep_rank))
        if not isinstance(rows, list): raise ValueError('missing EP rank parameter ledger')
        expected = {row['name']: row for row in rows}
        if len(expected) != len(rows): raise ValueError('duplicate manifest parameter name')
        live = {}
        seen_ids = set()
        for chunk_index, chunk in enumerate(model_chunks):
            if not isinstance(chunk, MCoreDDP): raise ValueError('actual MCore DDP required')
            model = chunk.module
            if isinstance(model, Float16Module): model = model.module
            if isinstance(model, (MCoreDDP, Float16Module)):
                raise ValueError('unexpected nested wrappers')
            if {id(p) for p in chunk.parameters() if p.requires_grad} != {id(p) for p in model.parameters() if p.requires_grad}:
                raise ValueError('DDP wrapper changed parameter ownership')
            for name, param in model.named_parameters():
                if not param.requires_grad or id(param) in seen_ids: continue
                seen_ids.add(id(param))
                key = f'chunk{chunk_index}/{name}'
                if key in live: raise ValueError('duplicate live parameter name')
                live[key] = param
        if not live or set(live) != set(expected): raise ValueError('live parameter coverage differs from reviewed ledger')
        bindings = {}
        for name, param in live.items():
            row = expected[name]
            if (param.device.type != 'cuda' or param.dtype != torch.bfloat16 or not param.is_contiguous()
                or list(param.shape) != row.get('shape') or list(param.stride()) != row.get('stride')
                or param.storage_offset() != row.get('storage_offset')):
                raise ValueError('live parameter geometry/dtype mismatch: ' + name)
            attrs, present = row.get('actual_attributes'), row.get('actual_attributes_present')
            keys = ('tensor_model_parallel', 'partition_dim', 'partition_stride', 'allreduce', 'sequence_parallel')
            if not isinstance(attrs, dict) or not isinstance(present, dict) or set(attrs) != set(keys) or set(present) != set(keys):
                raise ValueError('complete independently reviewed parameter attributes required')
            for key in keys:
                exists = hasattr(param, key)
                if type(present[key]) is not bool or exists != present[key] or (getattr(param, key, None) if exists else None) != attrs[key]:
                    raise ValueError('live parameter attribute mismatch: ' + name + ' ' + key)
            logical = row.get('logical_name')
            if not isinstance(logical, str) or not logical: raise ValueError('missing logical name')
            kind = row.get('kind')
            is_expert = not bool(getattr(param, 'allreduce', True))
            if kind == 'expert':
                if not is_expert:
                    raise ValueError('expert must use expert data-parallel ownership')
                # MCore marks row/column weights tensor_model_parallel=True even
                # for ETP1. The live ETP group size above proves no ETP slicing.
                coordinate = expert_coordinate(logical_name=logical, shape=tuple(param.shape),
                    layer=row.get('layer'), ep_rank=ep_rank, local_expert=row.get('local_expert'),
                    source_global_expert=row.get('source_global_expert'), tensor_kind=row.get('tensor_kind'))
                bindings[id(param)] = coordinate.to_sr_coordinates()
            elif kind in ('dense_replica', 'dense_tp_shard'):
                if is_expert: raise ValueError('dense entry identifies an expert-owned parameter')
                group_rank = dist.get_rank(ps.get_tensor_model_parallel_group())
                sharded = kind == 'dense_tp_shard'
                if bool(getattr(param, 'tensor_model_parallel', False)) != sharded:
                    raise ValueError('dense TP shard classification mismatch')
                bindings[id(param)] = make_fixed_tp4_coordinates(logical, tuple(param.shape), sharded=sharded,
                    group_rank=group_rank, axis=attrs['partition_dim'] if sharded else None,
                    stride=attrs['partition_stride'] if sharded else None)
            else:
                raise ValueError('unsupported reviewed parameter kind')
        names = [coordinate.canonical_name for coordinate in bindings.values()]
        if len(set(names)) != len(names): raise ValueError('duplicate logical SR coordinates on a rank')
    except BaseException as exc:
        error = exc
    flag = torch.tensor(int(error is None), dtype=torch.int32, device=torch.cuda.current_device())
    dist.all_reduce(flag, op=dist.ReduceOp.MIN)
    if not bool(flag.item()): raise RuntimeError('all-rank EP8 source/live binding failed') from error
    return bindings
